class DockerProvisioningReferenceTests(unittest.TestCase):
    """The entrypoint must not invent provisioning options or refuse zero."""

    @classmethod
    def setUpClass(cls):
        cls.migration = entrypoint_python("def rewrite(")
        cls.guard = entrypoint_python("def url_addresses(")

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)

    def run_migration(self, conf_text, hosts_text, server_ip):
        source = self.root / "dhcpd.conf"
        destination = self.root / "dhcpd.conf.new"
        hosts_source = self.root / "dhcpd.hosts"
        hosts_destination = self.root / "dhcpd.hosts.new"
        source.write_text(conf_text, encoding="utf-8")
        hosts_source.write_text(hosts_text, encoding="utf-8")
        result = subprocess.run(
            ["python3", "-c", self.migration, str(source), str(destination),
             str(hosts_source), str(hosts_destination), server_ip],
            capture_output=True, text=True, timeout=30,
        )
        return result, destination, hosts_destination

    def run_guard(self, conf_text, hosts_text, server_ip):
        conf = self.root / "guard-dhcpd.conf"
        hosts = self.root / "guard-dhcpd.hosts"
        conf.write_text(conf_text, encoding="utf-8")
        hosts.write_text(hosts_text, encoding="utf-8")
        return subprocess.run(
            ["python3", "-c", self.guard, str(conf), str(hosts), server_ip],
            capture_output=True, text=True, timeout=30,
        )

    def pool_block(self, subnet, provisioning_url=None, server_ip=None):
        lines = [f"subnet {subnet}.0 netmask 255.255.255.0 {{",
                 f"  range {subnet}.100 {subnet}.200;",
                 f"  option routers {subnet}.1;"]
        if provisioning_url:
            lines.append(f"  option www-server {server_ip};")
            lines.append(f'  option default-url "http://{server_ip}/";')
            lines.append(f'  option cumulus-provision-url "{provisioning_url}";')
        lines.append("}")
        return "\n".join(lines) + "\n"

    def test_a_config_where_no_pool_provisions_is_accepted(self):
        conf = self.pool_block("192.168.100") + self.pool_block("10.20.30")
        result, destination, _ = self.run_migration(conf, "", "192.168.100.7")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(destination.read_text(encoding="utf-8"), conf)

    def test_the_runtime_guard_also_accepts_a_zero_option_config(self):
        conf = self.pool_block("192.168.100") + self.pool_block("10.20.30")
        result = self.run_guard(conf, "", "192.168.100.7")
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_only_the_host_part_of_an_existing_option_is_rewritten(self):
        conf = self.pool_block(
            "192.168.100",
            "https://192.168.100.5:8443/ztp/cumulus-ztp.sh?role=leaf#top",
            "192.168.100.5",
        )
        result, destination, _ = self.run_migration(conf, "", "192.168.100.7")
        self.assertEqual(result.returncode, 0, result.stderr)
        migrated = destination.read_text(encoding="utf-8")
        self.assertIn(
            'option cumulus-provision-url '
            '"https://192.168.100.7:8443/ztp/cumulus-ztp.sh?role=leaf#top";',
            migrated,
        )
        self.assertIn("option www-server 192.168.100.7;", migrated)
        self.assertIn('option default-url "http://192.168.100.7/";', migrated)

    def test_a_pool_with_provisioning_off_gets_no_options_added(self):
        conf = (self.pool_block("192.168.100",
                                "http://192.168.100.5/cumulus-ztp.sh",
                                "192.168.100.5")
                + self.pool_block("10.20.30"))
        result, destination, _ = self.run_migration(conf, "", "192.168.100.7")
        self.assertEqual(result.returncode, 0, result.stderr)
        migrated = destination.read_text(encoding="utf-8")
        relayed = migrated[migrated.index("subnet 10.20.30.0"):]
        for option in ("www-server", "default-url", "cumulus-provision-url"):
            self.assertNotIn(option, relayed)

    def test_per_pool_values_are_not_flattened_into_one(self):
        conf = (self.pool_block("192.168.100",
                                "http://192.168.100.5/primary-ztp.sh",
                                "192.168.100.5")
                + self.pool_block("10.20.30",
                                  "http://192.168.100.5/relayed-ztp.sh",
                                  "192.168.100.5"))
        result, destination, _ = self.run_migration(conf, "", "192.168.100.7")
        self.assertEqual(result.returncode, 0, result.stderr)
        migrated = destination.read_text(encoding="utf-8")
        self.assertIn('"http://192.168.100.7/primary-ztp.sh"', migrated)
        self.assertIn('"http://192.168.100.7/relayed-ztp.sh"', migrated)

    def test_an_option_pointing_at_another_server_still_fails_the_guard(self):
        conf = self.pool_block("192.168.100",
                               "http://192.168.100.5/cumulus-ztp.sh",
                               "192.168.100.5")
        result = self.run_guard(conf, "", "192.168.100.7")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("www-server", result.stderr)

    def test_a_migrated_config_satisfies_the_guard(self):
        conf = self.pool_block("192.168.100",
                               "http://192.168.100.5/cumulus-ztp.sh",
                               "192.168.100.5")
        result, destination, _ = self.run_migration(conf, "", "192.168.100.7")
        self.assertEqual(result.returncode, 0, result.stderr)
        guard = self.run_guard(destination.read_text(encoding="utf-8"), "",
                               "192.168.100.7")
        self.assertEqual(guard.returncode, 0, guard.stderr)


