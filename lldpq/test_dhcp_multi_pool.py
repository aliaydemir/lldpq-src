#!/usr/bin/env python3
"""Checks the Provision DHCP server can serve more than one pool safely.

`dhcpd.conf` stays the single source of truth: it is rewritten from scratch on
every save and read back on every load.  That makes the reader the most
dangerous component in this feature.  Every installation written before this
change nests its single subnet inside `shared-network OOB { ... }`, so a reader
that only recognises a top-level `subnet` returns no pools, and the next save
writes a config with no subnet at all — silently deleting the pool the whole
fleet depends on.  The first class below pins that shape.

The rest covers what multiple pools introduce.  Pool 1 is directly attached and
must own an address on the listen interface; `dhcpd -t` performs no network
operation and a save made while the service is stopped never exercises
interface binding, so nothing but an application-level check notices when that
stops being true.  Pools 2..N are relayed: they are reachable only because an
external relay on another VLAN's gateway forwards requests here, which LLDPq
neither configures nor verifies.  A reservation that falls outside every pool,
or inside a pool's dynamic range, is not a syntax error either — dhcpd accepts
it and then never serves it.

The save paths are executed for real out of the CGI, against a temporary
filesystem, with a fake `ip` on PATH and the transaction/service helpers stubbed
out.  Packet-level relay behaviour cannot be tested here and stays a lab step.
"""

