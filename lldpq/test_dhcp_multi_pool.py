def extract_source(name: str) -> str:
    """Slice one top-level def or assignment out of the CGI's embedded Python."""
    for node in _TREE.body:
        if isinstance(node, ast.FunctionDef) and node.name == name:
            start = min([node.lineno] +
                        [decorator.lineno for decorator in node.decorator_list])
            return "\n".join(_BODY.splitlines()[start - 1:node.end_lineno]) + "\n"
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == name
            for target in node.targets
        ):
            return "\n".join(
                _BODY.splitlines()[node.lineno - 1:node.end_lineno]
            ) + "\n"
    raise AssertionError(f"{name} not found in provision-api.sh")


def heredoc_bodies(text: str, tag: str) -> list[str]:
    """Every `<<'TAG' ... TAG` payload, in source order."""
    opener = f"<<'{tag}'\n"
    closer = f"\n{tag}\n"
    bodies = []
    cursor = 0
    while True:
        start = text.find(opener, cursor)
        if start == -1:
            return bodies
        start += len(opener)
        end = text.index(closer, start)
        bodies.append(text[start:end])
        cursor = end


def entrypoint_python(marker: str) -> str:
    for body in heredoc_bodies(ENTRYPOINT, "PYTHON"):
        if marker in body:
            return body
    raise AssertionError(f"no embedded PYTHON block contains {marker!r}")


def shell_function(text: str, name: str) -> str:
    """Slice one shell function out, skipping over any heredoc it contains.

    Several of these functions emit a config with `}` lines of its own, so the
    first closing brace at column 0 is not the end of the function.
    """
    lines = text[text.index(f"{name}() {{"):].splitlines(keepends=True)
    collected = []
    terminator = None
    for line in lines:
        collected.append(line)
        if terminator is not None:
            if line.strip() == terminator:
                terminator = None
            continue
        opener = re.search(r"<<-?\s*'?([A-Za-z_][A-Za-z0-9_]*)'?", line)
        if opener:
            terminator = opener.group(1)
            continue
        if len(collected) > 1 and line.rstrip("\n") == "}":
            return "".join(collected)
    raise AssertionError(f"{name}() has no closing brace")


